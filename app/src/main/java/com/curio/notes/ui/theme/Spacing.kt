package com.curio.notes.ui.theme

import androidx.compose.ui.unit.dp

// Single spacing scale. Prefer these over ad-hoc dp literals so every
// screen shares the same rhythm: xs details, sm tight rows, md related
// groups, lg screen padding, xl/xxl section breaks.
object Spacing {
    val xs = 4.dp
    val sm = 8.dp
    val md = 12.dp
    val lg = 16.dp
    val xl = 24.dp
    val xxl = 32.dp
}
